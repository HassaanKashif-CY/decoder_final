import re
import smtplib
import ssl
import time
from email.message import EmailMessage
from pathlib import Path

from backend.core.config import get_settings


class EmailSenderError(Exception):
    pass


class EmailSender:
    MAX_ATTACHMENT_BYTES = 24 * 1024 * 1024  # Gmail limit is 25 MB total
    RETRIES = 2

    def __init__(self):
        self.settings = get_settings()

    @property
    def recipients(self) -> list[str]:
        return [
            email.strip()
            for email in self.settings.sahl_recipients.split(",")
            if email.strip()
        ]

    def send_submission(
        self,
        company_name: str,
        user_email: str,
        document_name: str,
        framework_name: str,
        requirement_count: int,
        pdf_path: str | Path,
        json_path: str | Path,
        csv_path: str | Path,
    ) -> list[str]:

        username = (self.settings.smtp_username or "").strip()
        # Gmail app passwords are shown with spaces; SMTP needs them removed.
        password = (self.settings.smtp_password or "").replace(" ", "")

        if not username:
            raise EmailSenderError("SMTP_USERNAME is not configured.")

        if not password:
            raise EmailSenderError("SMTP_PASSWORD is not configured.")

        recipients = self.recipients

        if not recipients:
            raise EmailSenderError("SAHL_RECIPIENTS is not configured.")

        subject_framework = self._clean_subject(
            framework_name or "Compliance Document"
        )

        message = EmailMessage()
        message["From"] = username
        message["To"] = ", ".join(recipients)
        message["Subject"] = (
            f"Sahl Compliance Decoder Submission - {subject_framework}"
        )

        if user_email and re.fullmatch(r"[^@\s]+@[^@\s]+\.[^@\s]+", user_email):
            message["Reply-To"] = user_email

        body = f"""
A new compliance document has been decoded and submitted through Sahl Compliance Decoder.

Submission Details
------------------
Company: {company_name or "Not provided"}
Business Email: {user_email or "Not provided"}

Document: {document_name}
Framework: {framework_name or "Not identified"}
Requirements / Controls: {requirement_count}

The following files are attached:

1. Original PDF
2. Complete JSON breakdown
3. CSV import file

The CSV is the import-friendly version.
The JSON preserves the complete decoded structure.

Generated by:
Sahl Compliance Decoder
"""

        message.set_content(body.strip(), charset="utf-8")

        files = [
            (Path(pdf_path), "application", "pdf"),
            (Path(json_path), "application", "json"),
            (Path(csv_path), "text", "csv"),
        ]

        total_size = 0

        for path, maintype, subtype in files:
            total_size += self._attach_file(
                message=message,
                path=path,
                maintype=maintype,
                subtype=subtype,
            )

        if total_size > self.MAX_ATTACHMENT_BYTES:
            raise EmailSenderError(
                f"Attachments are too large "
                f"({total_size / 1024 / 1024:.1f} MB). "
                f"Most SMTP servers reject more than ~25 MB."
            )

        self._send_with_retry(message, username, password)

        return recipients

    # ------------------------------------------------------------------
    # SMTP
    # ------------------------------------------------------------------

    def _send_with_retry(
        self,
        message: EmailMessage,
        username: str,
        password: str,
    ) -> None:

        last_error: Exception | None = None

        for attempt in range(1, self.RETRIES + 2):
            try:
                self._send_once(message, username, password)
                return

            except smtplib.SMTPAuthenticationError as exc:
                raise EmailSenderError(
                    "SMTP login rejected. For Gmail/Google Workspace use "
                    "an App Password (2-Step Verification must be on), "
                    f"not the normal account password. ({exc.smtp_code})"
                ) from exc

            except smtplib.SMTPRecipientsRefused as exc:
                raise EmailSenderError(
                    f"Recipient address rejected: {exc.recipients}"
                ) from exc

            except (
                smtplib.SMTPServerDisconnected,
                smtplib.SMTPConnectError,
                TimeoutError,
                ConnectionError,
                ssl.SSLError,
            ) as exc:
                last_error = exc

                if attempt <= self.RETRIES:
                    time.sleep(2 * attempt)
                    continue

            except Exception as exc:
                raise EmailSenderError(
                    f"Unable to send submission email: "
                    f"{type(exc).__name__}: {exc}"
                ) from exc

        raise EmailSenderError(
            f"Unable to send submission email after "
            f"{self.RETRIES + 1} attempts: "
            f"{type(last_error).__name__}: {last_error}. "
            f"Check SMTP_HOST ({self.settings.smtp_host}) and "
            f"SMTP_PORT ({self.settings.smtp_port}): use 587 for STARTTLS "
            f"or 465 for SSL, and check that antivirus/firewall is not "
            f"blocking outbound SMTP."
        ) from last_error

    def _send_once(
        self,
        message: EmailMessage,
        username: str,
        password: str,
    ) -> None:

        host = self.settings.smtp_host
        port = int(self.settings.smtp_port)
        context = ssl.create_default_context()

        if port == 465:
            # Implicit SSL. STARTTLS on this port makes the server hang up.
            with smtplib.SMTP_SSL(
                host, port, timeout=60, context=context
            ) as server:
                server.login(username, password)
                server.send_message(message)
            return

        with smtplib.SMTP(host, port, timeout=60) as server:
            server.ehlo()

            if server.has_extn("starttls"):
                server.starttls(context=context)
                server.ehlo()

            server.login(username, password)
            server.send_message(message)

    # ------------------------------------------------------------------
    # HELPERS
    # ------------------------------------------------------------------

    def _attach_file(
        self,
        message: EmailMessage,
        path: Path,
        maintype: str,
        subtype: str,
    ) -> int:

        if not path.exists():
            raise EmailSenderError(f"Attachment not found: {path}")

        data = path.read_bytes()

        message.add_attachment(
            data,
            maintype=maintype,
            subtype=subtype,
            filename=path.name,
        )

        return len(data)

    def _clean_subject(self, value: str) -> str:
        value = re.sub(r"[\r\n]+", " ", value)
        return value.strip()[:150]